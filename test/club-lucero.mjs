import assert from 'node:assert/strict';
process.env.GOY_THEFT_AUTO_MAP='brickell';
const {club,clubDoor,clubSolids,clubAisle,clubSeat,seatAtClub,leaveClubSeat,inBoothAisle}=await import('../public/club-lucero.js');
const {MAP,buildingTopAt}=await import('../public/world.js');
const {fanHall}=await import('../public/palma-site.js');
const {resortLevels}=await import('../public/grand-resort-layout.js');
const {landmarkGuide}=await import('../public/landmark-navigation.js');
const crossesClub=p=>Math.abs(p.x-club.x)<(club.w+p.w)/2 && Math.abs(p.z-club.z)<(club.d+p.d)/2;
assert(club.z+club.d/2<Math.min(...fanHall.map(([,z])=>z)));
assert(fanHall.some(([x])=>Math.abs(x-club.x)<club.w/2));
assert(!resortLevels.some(l=>l.parts.some(crossesClub)));
assert(!MAP.buildings.some(crossesClub));
assert(!MAP.barriers.some(p=>!clubSolids.includes(p) && crossesClub(p)));
assert.equal(clubDoor.z,club.z);
assert(clubDoor.x>club.x+club.w/2);
const route=landmarkGuide('Club Lucero')(0,15,0);
assert(Math.hypot(route.goal[0]-clubDoor.x,route.goal[1]-clubDoor.z)<2);
assert.deepEqual(route.line.at(-1),route.goal);
const actor=id=>({id,life:{hp:100},state:{...clubAisle,grounded:true},weapon:2});
const p=actor(1),q=actor(2),guests=new Map([[1,p],[2,q]]);
assert(buildingTopAt(club.x+4.82,club.z,.27,1.60)<1.0);
assert(buildingTopAt(club.x+4.82,club.z+2,.27,1.60)>3.0);
assert(buildingTopAt(club.x-3.43,club.z,0,1.5)>1);
assert(inBoothAisle(p.state));assert(seatAtClub(p,21,guests));assert.equal(p.state.x,clubSeat.x);
assert(!seatAtClub(q,22,guests));assert.equal(p.weapon,2);
leaveClubSeat(p);assert(inBoothAisle(p.state));assert(seatAtClub(q,23,guests));
leaveClubSeat(q);q.life.hp=0;assert(!seatAtClub(q,24,guests));
p.state.z=10;assert(!seatAtClub(p,25,guests));
console.log('PASS open club entrance, solid walls/stage, exclusive booth, equipment retention, leaving, range and life checks');
