import assert from 'node:assert/strict';
process.env.GOY_THEFT_AUTO_MAP='brickell';
const {newExpedition,fire,stepBurningActors}=await import('../public/expedition.js');
const {healthView,newLife}=await import('../public/rivals.js');
const world=newExpedition();
const actor=(id,z)=>({id,life:newLife(0,false),state:{x:0,y:1,z,grounded:true},yaw:0});
const player=Object.assign(actor(1,15),{weapon:5,fireReady:0,score:{kills:0,deaths:0}});
const civilian=actor('test-walker',12),other=actor(2,10);
const players=new Map([[1,player],[2,other]]),npcs=[civilian];
const cast=t=>fire(world,player,{aimYaw:0,aimPitch:0},t,players,npcs);
const step=t=>stepBurningActors(world,players,npcs,t);
cast(10);step(10);
assert.equal(healthView(civilian,10).burning,true);
assert.equal(civilian.life.hp,92);
assert.equal(other.life.hp,100,'first pedestrian shields the one behind');
cast(16);step(16);assert.equal(civilian.life.hp,92,'refresh never stacks damage');
step(25);assert.equal(civilian.life.hp,84);
civilian.state.swimming=true;step(26);assert.equal(healthView(civilian,26).burning,undefined);
civilian.state.x=8;other.life.immuneUntil=50;
cast(40);step(40);assert.equal(other.life.hp,100);
cast(50);step(50);assert.equal(other.life.hp,92);
for(let t=51;t<=145;t++)step(t);
assert.equal(other.life.hp,52);assert.equal(healthView(other,145).burning,undefined);
other.life.hp=5;cast(146);step(146);step(147);
assert.equal(other.life.hp,0);assert.equal(player.score.kills,1);
console.log('PASS actor ignition, closest contact, shield, damage cadence, immersion, expiry and defeat');
