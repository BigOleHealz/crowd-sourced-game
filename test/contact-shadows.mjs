import assert from 'node:assert/strict';
import {Scene,Mesh,BoxGeometry,MeshBasicMaterial,Matrix4} from 'three';
process.env.PINEWATCH_MAP='brickell';
const {contactShadows,furnitureFootprint}=await import('../public/contact-shadows.js');
const {furnitureRanges}=await import('../public/shop-furniture-view.js');
const {skyDarkness}=await import('../public/road-lighting.js');
const {groundHeight}=await import('../public/world.js');
const scene=new Scene(),contacts=contactShadows(scene),batch={positions:[]};
const motion=furnitureRanges(scene,[batch]),p={id:'chair',x:-11.18,z:4.10,w:.44,d:.42,height:.817,floor:.824};
const range=motion.start(p);batch.positions.push(0,0,0);motion.end(range);
const owner=new Mesh(new BoxGeometry(),new MeshBasicMaterial());scene.add(owner);motion.bind([owner]);
const car={x:-3,z:15,y:groundHeight(-3,15),yaw:0,flatTires:0};
const world={rover:car,doors:{}},local={x:-7,y:.8,z:8},feet={...local,grounded:true};
const rig={gait:{yaw:0},limbs:[{side:-1,foot:{wx:-6,wz:7.9,lift:0}},{side:1,foot:{wx:-5.74,wz:8.1,lift:.24}}]};
const mesh=scene.getObjectByName('Ground contact shadows');
const update=()=>{contacts.begin(world,local);contacts.boots(rig,feet,local);contacts.end(world,local);};update();
assert.equal(mesh.count,6,'four wheels, one grounded sole and chair');
const m=new Matrix4();mesh.getMatrixAt(5,m);assert(Math.abs(m.elements[12]-p.x)<.001);
world.doors.furniture={chair:{dx:1,dz:0,shift:.30,phase:1}};update();mesh.getMatrixAt(5,m);
const fallen=furnitureFootprint(p,world.doors.furniture.chair);
assert(Math.abs(m.elements[12]-fallen.x)<.001 && Math.abs(fallen.w-p.height)<1e-8);
owner.visible=false;feet.grounded=false;car.bridgeFlight={};update();assert.equal(mesh.count,0);
owner.visible=true;delete car.bridgeFlight;feet.grounded=true;world.doors.collapsedTowers=[4];update();assert.equal(mesh.count,5,'removed building leaves no chair shadow');
skyDarkness.value=1;assert.equal(mesh.material.uniforms.skyDarkness.value,1);
console.log('PASS one shadow batch for grounded tires, planted soles and transformed furniture, with hidden/removed/airborne and night cases.');

const {createRangerRig,poseRig}=await import('../public/ranger-pose.js');
const {castActorShadow}=await import('../public/actor-sun-shadow.js');
const avatar=createRangerRig(),walker={x:-2,y:.7,z:15,yaw:0,grounded:true,weapon:1};
poseRig(avatar,walker,1/60);
const cast=[];castActorShadow(avatar,walker,{doors:{}},(...args)=>cast.push(args));
assert.equal(cast.length,10);assert(cast.every(([x,y,z,yaw,w,d,a])=>[x,y,z,yaw,w,d,a].every(Number.isFinite)&&a<0));
assert(cast[1][0]>walker.x+.9 && cast[1][2]>walker.z+.5,'head shadow lies away from the sun');
const roofShadow={position:{set(x,y,z){this.y=y}},rotation:{},scale:{set(){}},material:{}};
avatar.shadow=roofShadow;poseRig(avatar,{...walker,y:17},1/60);assert.equal(roofShadow.position.y,17.026);
