import assert from 'node:assert/strict';
process.env.PINEWATCH_MAP='brickell';
const {newExpedition,fireTank,fireTurret,advanceRounds}=await import('../public/expedition.js');
const {gunnerFeet}=await import('../public/mounts.js');
const {newLife}=await import('../public/rivals.js');
const {selectSeat}=await import('../public/seat-selection.js');
const {nextUse}=await import('../public/use-target.js');
const {damageTank,leaveTank}=await import('../public/tank.js');
const {sampleRanger,J}=await import('../public/ragdoll.js');
const w=newExpedition(),t=w.tank;
Object.assign(t,{x:0,y:100,z:0,yaw:.2,turretYaw:.62,turretPitch:.11});
const actor=id=>({id,life:newLife(0,false),state:{x:t.x+2,y:t.y,z:t.z,grounded:true},yaw:0,inputs:[]});
const driver=actor(1),roof=actor(2),other=actor(3),players=new Map([driver,roof,other].map(p=>[p.id,p]));
assert.equal(nextUse(w,driver.state,driver.id,'tank').role,'drive');t.driver=driver.id;
assert.equal(nextUse(w,roof.state,roof.id,'tank').role,'gunner');t.gunner=roof.id;
assert.equal(nextUse(w,other.state,other.id,'tank'),null);
assert(!selectSeat(w,roof,'tank',1));assert(!selectSeat(w,driver,'tank',2));
Object.assign(t,{roofYaw:-.5,roofPitch:.21});
fireTank(w,driver,100);fireTurret(w,'tank',roof,100,players,[]);
assert.equal(w.bullets.length,1);assert.equal(w.missiles.length,1);
assert.ok(Math.abs(Math.atan2(w.bullets[0].vx,-w.bullets[0].vz)-t.roofYaw)<1e-6);
assert.equal(w.missiles[0].yaw,t.turretYaw);
w.bullets.length=0;
roof.state={...gunnerFeet(t,'tank'),grounded:true};
sampleRanger(roof,1/30,w,100);
const target=roof.hitPose.joints[J.head];
w.bullets.push({id:9,source:null,weapon:1,shooter:other.id,x:target.x,y:target.y,z:target.z+1,vx:0,vy:0,vz:-60,left:20,age:0});
advanceRounds(w,players,[],101);
assert(roof.life.hp<100);assert.equal(driver.life.hp,100);assert.equal(t.hp,t.maxHp);
assert(leaveTank(w,roof));assert.equal(t.driver,1);assert(selectSeat(w,driver,'tank',2));
assert.equal(t.driver,null);assert.equal(t.gunner,1);assert.equal(t.turretYaw,.62);
t.driver=other.id;damageTank(w,t.hp,players);
assert(t.wrecked);assert.equal(t.driver,null);assert.equal(t.gunner,null);
assert(Math.hypot(driver.state.x-t.x,driver.state.z-t.z)>1.2);assert(Math.hypot(other.state.x-t.x,other.state.z-t.z)>1.2);
console.log('Two exclusive tank seats, separate aim and fire, exposed roof hitbox, simultaneous wreck ejection.');
