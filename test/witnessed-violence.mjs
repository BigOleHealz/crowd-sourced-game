import assert from 'node:assert/strict';
import {localWorldReactions} from '../public/pedestrian-reactions.js';
import {damageActor,newLife} from '../public/rivals.js';

const actor=(id,x)=>({id,state:{x,y:1,z:0,grounded:true},life:newLife(0,false)});
const victim=actor('player',2),civilian=actor('witness',17),officer={...actor('officer',5),officer:true};
const distant=actor('distant',160),crowd=[civilian,officer,distant],players=new Map([[victim.id,victim]]);
const world={traffic:[],shots:[],doors:{}};
victim.life.immuneUntil=80;
damageActor(victim,10,50);
localWorldReactions(world,crowd,50,players);
assert.equal(world.panicCues.length,0);
damageActor(victim,10,82);
localWorldReactions(world,crowd,82,players);
assert.equal(civilian.reaction.type,'gunfire');
assert.equal(world.panicCues.length,1);
assert.equal(officer.reaction,undefined);
assert.equal(distant.reaction,undefined);
localWorldReactions(world,crowd,83,players);
assert.equal(world.panicCues.length,1);
world.dogs=[{id:'pip',x:150,y:1,z:0,lastHurtTick:90}];
localWorldReactions(world,crowd,90,players);
assert.equal(distant.reaction.type,'gunfire');
world.traffic.push({id:'sedan',x:7,y:1,z:0,takeover:{npcId:'driver'}});
localWorldReactions(world,crowd,98,players);
assert.equal(world.panicCues.length,3);
localWorldReactions(world,crowd,115,players);
assert.equal(world.panicCues.length,3);
console.log('Confirmed harm and car takeovers scatter nearby civilian witnesses once per event.');
