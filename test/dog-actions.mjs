import assert from 'node:assert/strict';
process.env.GOY_THEFT_AUTO_MAP='brickell';
const {newDogs}=await import('../public/dog-walkers.js');
const {requestDogAction}=await import('../dog-actions.js');
const {touchLayout}=await import('../public/touch-controls.js');
const walker={id:'rival-fern',yaw:0,state:{x:0,y:1,z:8}};
const world={dogs:newDogs([walker])},dog=world.dogs[0];
const player=id=>({id,yaw:0,state:{...walker.state},life:{hp:100}});
const a=player(1),b=player(2);
const send=(p,action,tick,overrides={})=>requestDogAction(world,p,{action,target:dog.id,yaw:0,pitch:.4,...overrides},tick);
send(a,'take',2,{target:'stale'});
assert.equal(dog.mode,'leashed');
a.state.x=10;
send(a,'take',3);
assert.equal(dog.mode,'leashed');
a.state.x=0;
send(a,'take',4);
send(b,'take',4);
assert.equal(dog.carrier,1);
send(a,'toss',5);
send(b,'toss',16);
send(a,'toss',16,{yaw:Infinity});
assert.equal(dog.carrier,1);
send(a,'toss',18);
assert.equal(dog.mode,'thrown');
assert.equal(dog.carrier,null);
const quick=touchLayout({role:'foot',use:'Steal dog',dogAction:'Kick dog'}).quick;
assert.deepEqual(quick.slice(0,2),[['KeyE','Steal dog'],['KeyX','Kick dog']]);
assert.equal(touchLayout({role:'foot',dogAction:'Throw dog'}).quick[0][1],'Throw dog');
assert.equal(touchLayout({role:'car'}).quick.some(([code])=>code==='KeyX'),false);
console.log('Dog actions respect range, target identity, ownership, tap cooldown and finite aim.');
