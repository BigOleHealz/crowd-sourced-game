import assert from 'node:assert/strict';
// Server and browser use these same map-specific simulation modules.
process.env.PINEWATCH_MAP='brickell';
const {newExpedition,fireTurret,advanceRounds}=await import('../public/expedition.js');
const {nearBoat,interactBoat,stepBoat,damageBoat,nearbyHull}=await import('../public/patrol-boats.js');
const {selectSeat}=await import('../public/seat-selection.js');
const {MAP,groundHeight}=await import('../public/world.js');
const {vehicleContact}=await import('../public/vehicle-contact.js');
const dt=1/30,world=newExpedition(),[bay,key]=world.boats;
const rider=id=>({id,weapon:1,fireReady:0,life:{hp:100},state:{x:42.7,y:.80,z:14,grounded:true}});
const a=rider(1),b=rider(2),c=rider(3),players=new Map([a,b,c].map(p=>[p.id,p]));
assert.equal(nearBoat(world,a.state),bay);
interactBoat(world,bay,a);interactBoat(world,bay,b);assert.equal(bay.driver,1);assert.equal(bay.gunner,2);
assert(!selectSeat(world,c,bay.id,2));assert(!selectSeat(world,b,bay.id,1));
interactBoat(world,bay,a);assert(a.state.grounded && a.state.x<=43,'shore exit');assert(!vehicleContact(a.state.x,a.state.y,a.state.z,world,true).depth);
assert(selectSeat(world,b,bay.id,1));assert.equal(bay.gunner,null);
Object.assign(a.state,{x:46.5,z:16.9,y:MAP.waterY-.72,grounded:false,swimming:true});
interactBoat(world,bay,a);assert.equal(bay.gunner,1);
for(let n=0;n<75;n++)stepBoat(world,bay,{throttle:1,steer:0},dt,players);
assert(bay.z<2 && bay.speed>10);assert.equal(key.z,-201);
Object.assign(key,{x:bay.x,z:bay.z-18});
bay.turretYaw=0;bay.turretPitch=-.055;
fireTurret(world,bay.id,a,100,players,[]);
assert.equal(world.bullets[0].source,bay.id);assert.equal(world.shots.at(-1).source,bay.id);
for(let n=0;n<18;n++)advanceRounds(world,players,[],101+n);
assert(key.hp<key.maxHp);assert.equal(bay.hp,bay.maxHp);
for(let n=0;n<60;n++)stepBoat(world,bay,{throttle:1},dt,players);
assert(!nearbyHull([key],bay,bay.x,bay.z,bay.yaw,1.04,2.65));assert(bay.hp<bay.maxHp);
damageBoat(world,bay,1000,players);assert(bay.wrecked && bay.driver===null && bay.gunner===null);
assert(a.state.grounded||a.state.swimming);assert(b.state.grounded||b.state.swimming);
for(let n=0;n<181;n++)stepBoat(world,bay,{},dt,players);
assert(!bay.wrecked && bay.hp===bay.maxHp && bay.x===46 && bay.z===14);
Object.assign(key,{x:66,z:-201,driver:3,yaw:-Math.PI/2});
for(let n=0;n<240;n++)stepBoat(world,key,{throttle:1},dt,players);
assert(groundHeight(key.x,key.z)<MAP.waterY-.24,'hull stays in navigable water');
console.log('PASS: two RHIBs, dry and swimming boarding, protected seat swaps, independent helm/turret, hull collision, damage, ejection, six-second recovery and beach clearance.');
