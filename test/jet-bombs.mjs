import assert from 'node:assert/strict';
import {newExpedition,dropJetBomb,launchMissile,advanceMissiles} from '../public/expedition.js';
const w=newExpedition(),pilot={id:1,life:{hp:100}},crew=new Map();
const jet=w.jet;
jet.pilot=pilot.id;
dropJetBomb(w,pilot,0);
assert.equal(w.missiles.length,0);
Object.assign(jet,{...w.rover,y:w.rover.y+9,pilot:1,pitch:0,yaw:0,speed:0,grounded:false});
dropJetBomb(w,{...pilot,id:2},0);
assert.equal(w.missiles.length,0);
dropJetBomb(w,pilot,0);dropJetBomb(w,pilot,1);
assert.equal(w.missiles.length,1);
const bomb=w.missiles[0];
launchMissile(w,'jet',pilot,0);
assert.equal(w.missiles.length,2);
w.missiles.pop();
jet.pilot=null;
const start=bomb.y,hp=w.rover.hp;
for(let t=1;t<90 && w.missiles.length;t++)advanceMissiles(w,crew,[],t);
assert(bomb.y<start && !w.missiles.length);
assert.equal(w.shots.filter(e=>e.weapon==='missile').length,1);
assert.equal(w.rover.hp,hp-150);
Object.assign(jet,{pilot:1,speed:30,pitch:Math.PI/6,yaw:Math.PI/2,y:60});
dropJetBomb(w,pilot,60);
const moving=w.missiles[0],x=moving.x,y=moving.y;
advanceMissiles(w,crew,[],61);
assert(moving.x>x+.8 && moving.y>y && moving.vy<15);
console.log('PASS pilot-only airborne bombs, independent cooldown, inherited motion, gravity and one damaging impact after bailout.');
